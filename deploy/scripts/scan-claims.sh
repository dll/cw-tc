#!/usr/bin/env bash
# 对外宣传禁词扫描：官网/落地页等**公开传播**文案不得出现保证性承诺与身份混淆表述。
# 用法：bash deploy/scripts/scan-claims.sh
#
# 这是 PRD v2 §9.12 与 AGENTS.md 铁律 13 的自动化门禁，CI 与上线前检查都会跑。
#
# 为什么单独做成一个门禁（而不是并入 scan-sensitive.sh）：
#   scan-sensitive.sh 管的是"**泄露个人隐私**"，本脚本管的是"**对外说错话**"——
#   前者是数据问题，后者是《广告法》第 9 条 / 第 24 条问题，两件事，失败原因必须一眼可辨。
set -euo pipefail

cd "$(dirname "$0")/../.."

# ---------------------------------------------------------------------------
# 扫描范围：**会被终端用户看到的公开文案**
#
#   docs/对外展示内容-v1.md   —— 官网与落地页文案的唯一出处
#   packages/app/lib          —— 学生端界面文案
#   packages/admin/src        —— 管理端界面文案（对外内容编辑页的默认文案与占位提示）
#   deploy/seed               —— 对外内容种子（web_content 初始数据）
#
# **不在范围**：PRD、数据字典、API 参考等内部文档 —— 它们必须能写出禁词才能定义禁词。
# ---------------------------------------------------------------------------
TARGETS=()
[[ -f docs/对外展示内容-v1.md ]] && TARGETS+=("docs/对外展示内容-v1.md")
[[ -d packages/app/lib ]] && TARGETS+=("packages/app/lib")
[[ -d packages/admin/src ]] && TARGETS+=("packages/admin/src")
[[ -d deploy/seed ]] && TARGETS+=("deploy/seed")

if [[ ${#TARGETS[@]} -eq 0 ]]; then
  echo "✗ 未找到任何扫描目标，脚本位置可能不对"
  exit 1
fi

# ---------------------------------------------------------------------------
# 禁词（PRD §9.12（一））
#   注意写法：不做裸 "第一 / 唯一 / 官方" 匹配 —— "第一次""唯一合法写法"是正常中文，
#   裸匹配会制造假警报，假警报多了门禁就会被绕过（这比没有门禁更糟）。
#   故只匹配**明确的广告式表述**。
# ---------------------------------------------------------------------------
PATTERN='包过|保过|保证通过|保证就业|包就业|学完即就业|对口就业'
PATTERN+='|国家级|最高级|最佳|最权威|顶级|领先|排名第一|行业第一|全国第一|第一名'
PATTERN+='|官方认证|国家认可|国家职业资格|职称|学信网|学历证书|保发证'
PATTERN+='|高薪|月薪|起薪|涨薪|年薪'

# ---------------------------------------------------------------------------
# 规则文本豁免：允许出现禁词的行 —— 该行本身在**说明禁令**
# （例如"不得出现'包过'等承诺性表述"）。这类行必须带下列标记之一。
# ---------------------------------------------------------------------------
RULE_LINE='禁词|禁用|禁止|不得|不许|不可以对外讲|不允许|红线|避免|违规'

# ---------------------------------------------------------------------------
# 区块豁免：允许整块出现禁词 —— 用 <!-- CLAIMS-ALLOW:BEGIN --> / END 包起来。
# 目前用于《对外展示内容》的"禁词表"本身（那几行就是禁词清单，必须写出来）。
# 豁免必须显式标注，且标注本身就是一次人工确认。
# ---------------------------------------------------------------------------
collect() {
  for f in "$@"; do
    [[ -f "$f" ]] && cat "$f"
    [[ -d "$f" ]] && find "$f" -type f \
      \( -name '*.dart' -o -name '*.ts' -o -name '*.vue' -o -name '*.js' -o -name '*.json' \) -print0 \
      | xargs -0 -r cat
  done
}

echo "==> 扫描对外宣传禁词（PRD §9.12）"
HITS=$(collect "${TARGETS[@]}" \
  | awk '/CLAIMS-ALLOW:BEGIN/{skip=1;next} /CLAIMS-ALLOW:END/{skip=0;next} skip==1{next} {print}' \
  | grep -vE "$RULE_LINE" \
  | grep -nE "$PATTERN" || true)

if [[ -n "$HITS" ]]; then
  echo "✗ 对外文案命中禁词（下列行既不在豁免区块，也不含禁令标记）："
  echo "$HITS"
  echo
  echo "处理方式（三选一，不要直接删掉门禁）："
  echo "  1) 改写表述；"
  echo "  2) 若在说明禁令，行内加'不得/禁止/禁词'等标记；"
  echo "  3) 若是禁词清单本身，用 <!-- CLAIMS-ALLOW:BEGIN --> / END 包住整块。"
  exit 1
fi
echo "✓ 未发现对外宣传禁词"

echo "==> 校验对外数字是否与上游一致（数字不得手改）"
if [[ -f tools/gen_public_content.py ]]; then
  if command -v python3 >/dev/null 2>&1; then
    python3 tools/gen_public_content.py --check || {
      echo "✗ 文档里的 AUTO 数字区块落后于上游，请重跑：python3 tools/gen_public_content.py"
      exit 1
    }
  else
    echo "（本机无 python3，跳过；CI 环境会执行）"
  fi
fi

echo "全部通过。"
